/*
 * One drill screen, and the five-state machine the spec's run lifecycle table describes.
 *
 * That table IS this file: which button is enabled, what the grid shows, and what a state
 * change does are the whole of what is written here. Everything a drill actually decides -
 * what a set is made of, what a tap does to a cell, whether that cell shows its value, what
 * the tally reads - is asked of DrillOps and DrillRun, so this screen holds no rule that a
 * JVM test would want to reach and none that could disagree with the stats table about the
 * same run.
 *
 * The clock is the one thing here that no pure layer can own: it reads the wall clock, which
 * is exactly why the pure layer takes elapsed time as a number instead.
 */
